//! Palettes ready to load: plain ones, ones pixel artists made, credited to them, and
//! those of old computers and consoles. The artists' and the hardware's come from
//! Lospec's palette list (lospec.com/palette-list).

use crate::Palette;
use image::Rgba;

/// A palette ready to load.
pub struct Preset {
    pub name: &'static str,
    /// Who made it, if anyone is credited.
    pub author: &'static str,
    /// Which list it is in: [`PRESET_GROUPS`].
    pub group: &'static str,
    codes: &'static [u32],
}

impl Preset {
    /// How many colours it has.
    pub fn color_count(&self) -> usize {
        self.codes.len()
    }

    pub fn palette(&self) -> Palette {
        Palette::new(self.codes.iter().map(|&code| from_code(code)).collect())
    }
}

pub(crate) const fn from_code(code: u32) -> Rgba<u8> {
    let [_, red, green, blue] = code.to_be_bytes();
    Rgba([red, green, blue, 255])
}

